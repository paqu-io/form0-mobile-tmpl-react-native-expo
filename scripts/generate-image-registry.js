#!/usr/bin/env node
/**
 * Auto-generate Supporting Images Registry
 *
 * This script scans the assets/supporting-images folder and generates
 * the registry file automatically. Run this after adding new images.
 *
 * Usage:
 *   node scripts/generate-image-registry.js
 *   # or
 *   npm run generate-images
 */

const fs = require('fs');
const path = require('path');

const IMAGES_DIR = path.join(__dirname, '..', 'assets', 'supporting-images');
const OUTPUT_FILE = path.join(__dirname, '..', 'src', 'supporting-images', 'index.js');

// Supported image extensions
const IMAGE_EXTENSIONS = ['.jpg', '.jpeg', '.png', '.gif', '.webp', '.svg', '.bmp'];

function generateRegistry() {
  // Check if images directory exists
  if (!fs.existsSync(IMAGES_DIR)) {
    console.log(`Creating images directory: ${IMAGES_DIR}`);
    fs.mkdirSync(IMAGES_DIR, { recursive: true });
  }

  // Get all image files
  const files = fs.readdirSync(IMAGES_DIR).filter((file) => {
    const ext = path.extname(file).toLowerCase();
    return IMAGE_EXTENSIONS.includes(ext);
  });

  console.log(`Found ${files.length} image(s) in ${IMAGES_DIR}`);

  // Generate require statements
  const requireStatements = files
    .map((file) => `  '${file}': require('../../assets/supporting-images/${file}'),`)
    .join('\n');

  // Generate the registry file content
  const content = `/**
 * Supporting Images Registry (Auto-generated)
 *
 * DO NOT EDIT THIS FILE MANUALLY!
 * This file is auto-generated by: npm run generate-images
 *
 * To add new images:
 * 1. Add your image files to: assets/supporting-images/
 * 2. Run: npm run generate-images
 *
 * Generated: ${new Date().toISOString()}
 * Images found: ${files.length}
 */

const supportingImages = {
${requireStatements}
};

/**
 * Resolve a supporting image path to its bundled source.
 *
 * @param {string} imagePath - The image path from the schema (e.g., "palette.jpg")
 * @returns {number | { uri: string } | null} - The image source for React Native Image component
 */
export function resolveSupportingImage(imagePath) {
  if (!imagePath) return null;

  // If it's a remote URL, return as-is in uri format
  if (imagePath.startsWith('http://') || imagePath.startsWith('https://')) {
    return { uri: imagePath };
  }

  // Look up in registry
  const source = supportingImages[imagePath];
  if (source) {
    return source;
  }

  // Try with just the filename (in case path includes directories)
  const filename = imagePath.split('/').pop();
  if (filename && supportingImages[filename]) {
    return supportingImages[filename];
  }

  console.warn(\`Supporting image not found in registry: \${imagePath}. Run 'npm run generate-images' to update.\`);
  return null;
}

/**
 * Get all registered image paths
 */
export function getRegisteredImages() {
  return Object.keys(supportingImages);
}

export default supportingImages;
`;

  // Ensure output directory exists
  const outputDir = path.dirname(OUTPUT_FILE);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  // Write the file
  fs.writeFileSync(OUTPUT_FILE, content, 'utf-8');

  console.log(`✅ Generated registry at: ${OUTPUT_FILE}`);
  if (files.length > 0) {
    console.log('\nRegistered images:');
    files.forEach((file) => console.log(`  - ${file}`));
  } else {
    console.log('\n⚠️  No images found. Add images to assets/supporting-images/');
  }
}

// Run the generator
generateRegistry();
